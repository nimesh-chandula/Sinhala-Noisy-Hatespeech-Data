"""
Character Error Rate of each romanizer backend against the gold set.
Lower is better. Target < 0.10, gated on `word_multi_min`.

CER is computed over GRAPHEME CLUSTERS, not codepoints — Sinhala syllables
are multi-codepoint, so codepoint-level CER would misjudge them — see
src/graphemes.py.

Gold set lives in data/gold/, built by scripts/fetch_data.py from two Swa-
Bhasha sources with different properties:

  - gold_words.jsonl: 2000 sampled Sinhala words, each with its full set of
    ATTESTED romanizations (combinatorially generated by the Swa-Bhasha
    authors — this is an enumeration of the plausible romanization space,
    not a single "correct answer"). Since Sinhala->Roman is genuinely
    one-to-many, single-reference CER unfairly penalizes a romanizer that
    picks a different-but-valid spelling. We therefore score:
      - word_multi_min: CER against the CLOSEST attested variant (primary)
      - word_single:    CER against one arbitrary (sorted-first) variant,
                        kept only as a diagnostic showing how much the
                        multi-reference credit actually matters
  - gold_sentences.jsonl: 400 real held-out human-typed sentence pairs
      - sent_single: CER against the one real sentence (no variants to
        choose from here, so this is the honest single-reference score)

Each registered backend is a callable: sinhala_text -> romanized_text.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.graphemes import clusters  # noqa: E402

GOLD_DIR = REPO_ROOT / "data" / "gold"
GOLD_WORDS_PATH = GOLD_DIR / "gold_words.jsonl"
GOLD_SENTENCES_PATH = GOLD_DIR / "gold_sentences.jsonl"


def edit_distance(a: list[str], b: list[str]) -> int:
    """Levenshtein distance between two sequences of grapheme clusters.

    Plain O(len(a)*len(b)) DP — gold items are short (words/sentences), so
    this is fast enough without an external dependency doing the actual
    distance math (python-Levenshtein operates on codepoints, which would
    silently reintroduce the mid-syllable-split bug this module exists to
    avoid).
    """
    if a == b:
        return 0
    n, m = len(a), len(b)
    if n == 0:
        return m
    if m == 0:
        return n
    prev = list(range(m + 1))
    curr = [0] * (m + 1)
    for i in range(1, n + 1):
        curr[0] = i
        ai = a[i - 1]
        for j in range(1, m + 1):
            cost = 0 if ai == b[j - 1] else 1
            curr[j] = min(
                prev[j] + 1,       # deletion
                curr[j - 1] + 1,   # insertion
                prev[j - 1] + cost,  # substitution
            )
        prev, curr = curr, prev
    return prev[m]


def levenshtein(a: str, b: str) -> int:
    """Grapheme-cluster edit distance between two raw strings."""
    return edit_distance(clusters(a), clusters(b))


def cer(hypothesis: str, reference: str) -> float:
    """Character Error Rate = edit_distance(hyp, ref) / len(ref), in grapheme clusters."""
    ref_clusters = clusters(reference)
    if not ref_clusters:
        return 0.0
    hyp_clusters = clusters(hypothesis)
    return edit_distance(hyp_clusters, ref_clusters) / len(ref_clusters)


def cer_multi_min(hypothesis: str, references: list[str]) -> float:
    """CER against whichever reference in `references` is closest.

    Correct treatment of a one-to-many gold set: a romanizer should not be
    penalized for producing a DIFFERENT valid romanization than the one
    arbitrarily listed first.
    """
    if not references:
        return 0.0
    return min(cer(hypothesis, ref) for ref in references)


def load_gold_words() -> list[dict]:
    """[{sinhala, romanizations: [...]}, ...] from data/gold/gold_words.jsonl."""
    if not GOLD_WORDS_PATH.exists():
        return []
    out = []
    with GOLD_WORDS_PATH.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def load_gold_sentences() -> list[dict]:
    """[{romanized, sinhala}, ...] from data/gold/gold_sentences.jsonl."""
    if not GOLD_SENTENCES_PATH.exists():
        return []
    out = []
    with GOLD_SENTENCES_PATH.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def load_gold() -> list[tuple[str, str]]:
    """Backward/contract-compatible flat view: [(sinhala, gold_romanized), ...].

    Uses the sentence-level gold (one real reference each) since this shape
    only has room for a single reference per item. For the full multi-
    reference word-level picture use `load_gold_words()` directly.
    """
    return [(row["sinhala"], row["romanized"]) for row in load_gold_sentences()]


UOM_LIVE_CACHE_PATH = REPO_ROOT / "data" / "gold" / "uom_live_bakeoff.jsonl"
_uom_live_cache: dict[str, str] | None = None


def _load_uom_live_cache() -> dict[str, str]:
    """Load the ONE-TIME bulk fetch of the real UoM site's output over the
    full gold set (scripts/fetch_uom_bakeoff.py — a deliberate, one-time
    exception to the "no live calls in the loop" rule, made once and
    cached). This function only ever reads that cache; it never calls the
    network, which is what keeps every subsequent harness run compliant with the
    rule."""
    global _uom_live_cache
    if _uom_live_cache is None:
        if UOM_LIVE_CACHE_PATH.exists():
            with UOM_LIVE_CACHE_PATH.open(encoding="utf-8") as f:
                _uom_live_cache = {
                    row["sinhala"]: row["live_output"]
                    for row in (json.loads(line) for line in f if line.strip())
                }
        else:
            _uom_live_cache = {}
    return _uom_live_cache


def _romanize_uom_live(sinhala_text: str) -> str:
    """Look up the cached real UoM site output for `sinhala_text`. Every
    gold-set item is expected to be present (the cache was built from the
    exact same gold set) — an empty string signals a cache miss, which
    would show up as a maximal CER for that item rather than crashing."""
    return _load_uom_live_cache().get(sinhala_text, "")


def discover_backends() -> dict[str, callable]:
    """Return {backend_name: romanize_fn} — the Phase 1 bake-off candidates.

    Each import is wrapped in try/except ImportError so a missing dependency
    degrades gracefully (harness still runs, that backend just doesn't
    appear) rather than crashing. See src/romanizers/{uom_rules,
    aksharamukha,indic}.py docstrings for what each candidate is and why:
      - uom_live: the REAL UoM site's output, from a one-time cached bulk
        fetch (scripts/fetch_uom_bakeoff.py) over the full gold set — not a
        loop call, see _load_uom_live_cache() docstring
      - uom_rules: hand-built local reimplementation, calibrated once
        against a 20-item sample of the live UoM endpoint — kept alongside
        uom_live so the two can be compared directly at full gold-set scale
      - aksharamukha_colloquial / aksharamukha_loc: aksharamukha PyPI library
      - singlish_pypi: vendored asanka9/singlish, wrapped to fix a real
        space/punctuation-dropping bug (registered from indic.py — see that
        module's docstring for why indic-transliteration was rejected)
    """
    backends: dict[str, callable] = {}

    if UOM_LIVE_CACHE_PATH.exists():
        backends["uom_live"] = _romanize_uom_live

    try:
        from src.romanizers.uom_rules import romanize as uom_romanize

        backends["uom_rules"] = uom_romanize
    except ImportError:
        pass

    try:
        from src.romanizers.aksharamukha import (
            romanize_colloquial,
            romanize_colloquial_raw,
            romanize_loc,
        )

        backends["aksharamukha_colloquial"] = romanize_colloquial
        backends["aksharamukha_colloquial_raw"] = romanize_colloquial_raw
        backends["aksharamukha_loc"] = romanize_loc
    except ImportError:
        pass

    try:
        from src.romanizers.indic import romanize as singlish_romanize

        backends["singlish_pypi"] = singlish_romanize
    except ImportError:
        pass

    return backends


def _score_backend(fn: callable, gold_words: list[dict], gold_sentences: list[dict]) -> dict[str, float]:
    word_multi_scores = []
    word_single_scores = []
    for entry in gold_words:
        romanizations = entry["romanizations"]
        if not romanizations:
            continue
        hyp = fn(entry["sinhala"])
        word_multi_scores.append(cer_multi_min(hyp, romanizations))
        word_single_scores.append(cer(hyp, romanizations[0]))

    sent_scores = []
    for entry in gold_sentences:
        hyp = fn(entry["sinhala"])
        sent_scores.append(cer(hyp, entry["romanized"]))

    def avg(xs):
        return sum(xs) / len(xs) if xs else None

    return {
        "word_multi_min": avg(word_multi_scores),
        "word_single": avg(word_single_scores),
        "sent_single": avg(sent_scores),
    }


def run_gold_cer_detail() -> dict[str, dict[str, float]]:
    """{backend_name: {word_multi_min, word_single, sent_single}}."""
    gold_words = load_gold_words()
    gold_sentences = load_gold_sentences()
    backends = discover_backends()
    if not backends or (not gold_words and not gold_sentences):
        return {}
    return {name: _score_backend(fn, gold_words, gold_sentences) for name, fn in backends.items()}


def run_gold_cer() -> dict[str, float]:
    """{backend_name: primary_cer} — primary metric is word_multi_min.

    This is the float the evaluation contract and the Phase 1 target
    (< 0.10) are gated on. See run_gold_cer_detail() for the full
    breakdown.
    """
    detail = run_gold_cer_detail()
    out = {}
    for name, scores in detail.items():
        primary = scores.get("word_multi_min")
        if primary is not None:
            out[name] = primary
    return out
